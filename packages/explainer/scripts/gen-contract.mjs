/**
 * gen-contract.mjs — EMIT the authoring contract as files, and prove they are true.
 *
 * These are the artifacts a generator (an LLM, a Studio panel, a partner) reads.
 * They are GENERATED from the engine, never hand-written, so they cannot describe
 * a template that moved. And every example in them is run through the real gate
 * before it is written: a few-shot that the gate would reject is worse than no
 * few-shot at all, because it teaches the model to produce exactly the scene that
 * will then be thrown away.
 *
 *   contract/AUTHORING.md          ← the prompt block (human + LLM readable)
 *   contract/catalog.json          ← machine-readable slots + measured budgets
 *   contract/scene-draft.schema.json ← JSON Schema for constrained decoding
 *   contract/examples.json         ← one gate-passing scene per template
 *
 * Run: pnpm --filter @bingoo.ai/explainer contract
 */
import { writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { z } from 'zod'
import {
  authoringGuide,
  templateCatalog,
  checkScene,
  SceneDraft,
  TEMPLATES,
  SLOT_META,
} from '../src/index.ts'
import { EXAMPLES } from '../src/examples.ts'

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'contract')
mkdirSync(OUT, { recursive: true })

const catalog = templateCatalog()

/* ── 1. the prompt block ─────────────────────────────────────────────────── */
const md = [
  '<!-- GENERATED by scripts/gen-contract.mjs — DO NOT EDIT.',
  '     Derived from layout.ts + type.ts, so the slot names and the character',
  '     budgets below are the SAME numbers the renderer draws with. -->',
  '',
  authoringGuide(),
  '',
  '# VÍ DỤ MẪU (few-shot)',
  '',
  'Mỗi ví dụ dưới đây đã CHẠY QUA GATE và đạt 0 lỗi. Copy hình dạng của chúng.',
  '',
]
for (const [tpl, ex] of Object.entries(EXAMPLES)) {
  md.push(
    `## ${tpl}`,
    `> ${ex.why}`,
    '',
    '```json',
    JSON.stringify({ scene: ex.scene, strings: ex.strings }, null, 2),
    '```',
    '',
  )
}
writeFileSync(join(OUT, 'AUTHORING.md'), md.join('\n'))

/* ── 2. machine-readable catalog ─────────────────────────────────────────── */
writeFileSync(
  join(OUT, 'catalog.json'),
  JSON.stringify(
    {
      $comment: 'GENERATED from layout.ts — maxChars is MEASURED at the tighter of 16:9 / 9:16.',
      rules: [
        'NEVER emit x, y, size, w, h, place or overrides. The engine computes every rect.',
        'Each element declares `region` = a slot name from this catalog. An unknown slot is a broken scene.',
        'Elements in an ordered slot (steps, grid, stats) must also set flow.order = 1..n.',
        "Text longer than a slot's maxChars is rejected: cut words, do not shrink type.",
        'Charts: emit `series` only. Bar heights, pie angles and axis ticks are derived.',
      ],
      templates: catalog,
    },
    null,
    2,
  ),
)

/* ── 3. JSON Schema for constrained decoding ─────────────────────────────── */
const schema = z.toJSONSchema(SceneDraft, { io: 'input' })
schema.$comment =
  'GENERATED. Note what is ABSENT: place, x, y, size, w, h, overrides. A model cannot emit a coordinate because there is nowhere to put one.'
schema.properties.template.enum = catalog.map((t) => t.template)
writeFileSync(join(OUT, 'scene-draft.schema.json'), JSON.stringify(schema, null, 2))

/* ── 4. examples — VERIFIED against the real gate before they are written ── */
let bad = 0
const examples = {}
for (const [tpl, ex] of Object.entries(EXAMPLES)) {
  const errs = checkScene(ex.scene, ex.strings).filter((f) => f.level === 'error')
  if (errs.length) {
    bad++
    console.error(`✗ ví dụ "${tpl}" KHÔNG qua gate:`)
    for (const e of errs) console.error(`    ${e.code}: ${e.message}`)
    continue
  }
  examples[tpl] = { why: ex.why, scene: ex.scene, strings: ex.strings }
}
writeFileSync(
  join(OUT, 'examples.json'),
  JSON.stringify(
    {
      $comment: 'GENERATED. Every scene here passes checkScene() with 0 errors at both aspects.',
      examples,
    },
    null,
    2,
  ),
)

/* ── coverage: a template with no example is a template the model will guess at */
const missing = TEMPLATES.filter((t) => !SLOT_META[t].use.startsWith('LEGACY') && !EXAMPLES[t])

if (bad) {
  console.error(`\n✗ ${bad} ví dụ không qua gate — sửa examples.ts`)
  process.exit(1)
}
console.log(
  `✓ contract/ đã xuất — ${catalog.length} template · ${Object.keys(examples).length} ví dụ, tất cả qua gate`,
)
if (missing.length) console.log(`  ⚠ chưa có ví dụ cho: ${missing.join(', ')}`)
