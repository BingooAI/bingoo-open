// @bingoo/tokens — build step.
// Reads src/tokens.json (single source of truth) and generates:
//   dist/tokens.css         → Tailwind v4 @theme + semantic themes (web)
//   dist/tokens.ts          → JS mirror (native, meta theme-color, tests)
//   dist/native/theme.js    → resolved light/dark theme + `vars()` maps (RN)
//   dist/native/preset.cjs  → NativeWind/Tailwind preset (RN, semantic classes)
// Run: `pnpm --filter @bingoo/tokens build`. Never edit dist/* by hand.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(readFileSync(join(root, 'src/tokens.json'), 'utf8'));

/** Resolve `{group.shade}` references to a CSS `var(--color-group-shade)`. */
const toCss = (value) => value.replace(/\{([a-z]+)\.(\w+)\}/g, 'var(--color-$1-$2)');
/** Resolve `{group.shade}` (or a literal) to its concrete hex, for the JS mirror. */
const toHex = (value) =>
  value.replace(/\{([a-z]+)\.(\w+)\}/g, (_, g, s) => {
    const hex = t.color[g]?.[s];
    if (!hex) throw new Error(`Unknown token reference {${g}.${s}}`);
    return hex;
  });

const GENERATED = '/* GENERATED by @bingoo/tokens build — DO NOT EDIT. Edit src/tokens.json. */';

/* ----------------------------- CSS output ------------------------------ */
const line = (k, v) => `  --${k}: ${v};`;
const themeLines = [];
themeLines.push(line('font-display', t.font.display));
themeLines.push(line('font-sans', t.font.sans));
for (const [k, [size, lh]] of Object.entries(t.text)) {
  themeLines.push(line(`text-${k}`, size), line(`text-${k}--line-height`, lh));
}
for (const [k, v] of Object.entries(t.radius)) themeLines.push(line(`radius-${k}`, v));
for (const [k, v] of Object.entries(t.shadow)) themeLines.push(line(`shadow-${k}`, v));
for (const [k, v] of Object.entries(t.ease)) themeLines.push(line(`ease-${k}`, v));
for (const [k, v] of Object.entries(t.animate)) themeLines.push(line(`animate-${k}`, v));
for (const [group, shades] of Object.entries(t.color))
  for (const [shade, hex] of Object.entries(shades))
    themeLines.push(line(`color-${group}-${shade}`, hex));

const semanticBlock = (map) =>
  Object.entries(map)
    .map(([k, v]) => line(k, toCss(v)))
    .join('\n');

const inlineMap = t.colorTokens.map((k) => line(`color-${k}`, `var(--${k})`)).join('\n');

// Foundations consumed via var(): z-index scale, motion durations, and the
// base style-pack skin tokens (radius-card, btn-depth, border-w, motion-scale).
const foundationVars = [
  ...Object.entries(t.zIndex).map(([k, v]) => line(`z-${k}`, v)),
  ...Object.entries(t.duration).map(([k, v]) => line(`dur-${k}`, v)),
  ...Object.entries(t.packs.base).map(([k, v]) => line(k, v)),
].join('\n');

// Each style-pack overrides the same skin tokens; toggle via `data-pack`.
const packBlocks = Object.entries(t.packs)
  .filter(([name]) => name !== 'base')
  .map(
    ([name, map]) =>
      `[data-pack='${name}'] {\n${Object.entries(map)
        .map(([k, v]) => line(k, v))
        .join('\n')}\n}`,
  )
  .join('\n\n');

// Accent packs re-hue the `primary`/`ring` family; toggle via `data-accent`
// (default = blue). Each ships light + dark so it stays legible in both themes.
const accentBlocks = Object.entries(t.accents ?? {})
  .flatMap(([name, modes]) => [
    `[data-accent='${name}'] {\n${semanticBlock(modes.light)}\n}`,
    `[data-theme='dark'] [data-accent='${name}'] {\n${semanticBlock(modes.dark)}\n}`,
  ])
  .join('\n\n');

const keyframes = `@keyframes float { 0%,100% { transform: translateY(0); } 50% { transform: translateY(-12px); } }
@keyframes bob { 0%,100% { transform: translateY(0) rotate(-1deg); } 50% { transform: translateY(-6px) rotate(1deg); } }
@keyframes pop-in { 0% { opacity: 0; transform: scale(0.94) translateY(6px); } 100% { opacity: 1; transform: scale(1) translateY(0); } }
@keyframes fade-up { 0% { opacity: 0; transform: translateY(14px); } 100% { opacity: 1; transform: translateY(0); } }
@keyframes shimmer { 0% { background-position: -200% 0; } 100% { background-position: 200% 0; } }
@keyframes wiggle { 0%,100% { transform: rotate(0); } 25% { transform: rotate(-6deg); } 75% { transform: rotate(6deg); } }
@keyframes slide-in-right { from { transform: translateX(100%); } to { transform: translateX(0); } }
@keyframes slide-out-right { from { transform: translateX(0); } to { transform: translateX(100%); } }
@keyframes slide-in-left { from { transform: translateX(-100%); } to { transform: translateX(0); } }
@keyframes slide-out-left { from { transform: translateX(0); } to { transform: translateX(-100%); } }
@keyframes fade-in { from { opacity: 0; } to { opacity: 1; } }
@keyframes fade-out { from { opacity: 1; } to { opacity: 0; } }
@keyframes dots-drift { from { background-position: 0 0; } to { background-position: 44px 44px; } }
@keyframes confetti-fall { 0% { transform: translateY(-12%) rotate(0deg); opacity: 1; } 100% { transform: translateY(118vh) rotate(680deg); opacity: 0.85; } }
@keyframes count-pop { 0% { transform: scale(1); } 40% { transform: scale(1.28); } 100% { transform: scale(1); } }`;

const css = `${GENERATED}

@theme {
${themeLines.join('\n')}
}

${keyframes}

/* Enable \`dark:\` utilities driven by the data-theme attribute. */
@custom-variant dark (&:where([data-theme='dark'], [data-theme='dark'] *));

:root,
[data-theme='light'] {
  color-scheme: light;
${semanticBlock(t.semantic.light)}
}

[data-theme='dark'] {
  color-scheme: dark;
${semanticBlock(t.semantic.dark)}
}

/* Map semantic tokens onto Tailwind color utilities (live, theme-swappable). */
@theme inline {
${inlineMap}
}

/* Foundations: z-index, motion durations, and the base style-pack skin tokens.
   Base applies on :root; each pack overrides the same tokens via data-pack. */
:root {
${foundationVars}
}

${packBlocks}

/* Accent packs (data-accent) — re-hue primary/ring in both light & dark. */
${accentBlocks}

/* A11y: reduced-motion zeroes the motion scale (wins over any active pack). */
@media (prefers-reduced-motion: reduce) {
  :root,
  [data-pack] {
    --motion-scale: 0 !important;
  }
}
`;

/* ------------------------------ TS output ------------------------------ */
const brand = Object.fromEntries(Object.entries(t.js.brand).map(([k, v]) => [k, toHex(v)]));
const themeColor = Object.fromEntries(
  Object.entries(t.js.themeColor).map(([k, v]) => [k, toHex(v)]),
);

const ts = `${GENERATED}

/**
 * Bingoo design tokens — JS mirror. Generated from tokens.json so it never
 * drifts from the CSS. Use for native themes, meta theme-color, canvas, tests.
 */
export const brand = ${JSON.stringify(brand, null, 2)} as const;

export const themeColor = ${JSON.stringify(themeColor, null, 2)} as const;

export const font = {
  display: ${JSON.stringify(t.js.fontDisplay)},
  text: ${JSON.stringify(t.js.fontText)},
} as const;

export const radius = ${JSON.stringify(t.radius, null, 2)} as const;

export type BrandColor = keyof typeof brand;
`;

/* --------------------------- Native output ----------------------------- */
// React Native has no CSS cascade, so we can't ship `data-theme`/`data-pack`
// selectors. Instead we resolve every semantic color token to a concrete value
// per theme and expose two things the mobile app consumes:
//   • `themeVars.{light,dark}` — plain `--color-*` maps fed to NativeWind's
//     `vars()` on a wrapper View, so `bg-primary`/`text-foreground` swap by theme.
//   • `lightTheme`/`darkTheme` — the same values as an object, for the few native
//     APIs that need a raw color (StatusBar, LinearGradient, navigation theme).
// The NativeWind preset points each semantic class at `var(--color-*)`; the vars
// come from `vars()`. Packs/accents (attribute-scoped on web) are deferred for
// native — the same `vars()` mechanism will layer them later.

const REM = 16;
const remToPx = (v) =>
  typeof v === 'string' && v.endsWith('rem') ? `${parseFloat(v) * REM}px` : v;
const remToNum = (v) =>
  typeof v === 'string' && v.endsWith('rem')
    ? parseFloat(v) * REM
    : typeof v === 'string' && v.endsWith('px')
      ? parseFloat(v)
      : v;

// Resolve a semantic token value to a concrete color string (leaves rgb()/hex as
// is, expands {group.shade} refs). Gradients are handled separately.
const resolveColor = (value) => toHex(value);
// Pull the ordered color stops out of a `linear-gradient(<angle>, stopA, stopB)`.
// Each stop is a color optionally followed by a position (e.g. `#eaf1ff 0%`).
const gradientStops = (value) => {
  const inner = value.slice(value.indexOf('(') + 1, value.lastIndexOf(')'));
  return inner
    .split(',')
    .map((s) => s.trim())
    .filter((s) => !s.endsWith('deg')) // drop the leading angle
    .map((s) => s.split(/\s+/)[0]) // color, without any trailing position
    .map((s) => toHex(s));
};

const themeVarsFor = (mode) =>
  Object.fromEntries(
    t.colorTokens.map((k) => {
      const raw = t.semantic[mode][k] ?? t.semantic.light[k];
      return [`--color-${k}`, resolveColor(raw)];
    }),
  );
const themeObjectFor = (mode) =>
  Object.fromEntries(
    t.colorTokens.map((k) => [k, resolveColor(t.semantic[mode][k] ?? t.semantic.light[k])]),
  );

const themeVars = { light: themeVarsFor('light'), dark: themeVarsFor('dark') };
const lightTheme = themeObjectFor('light');
const darkTheme = themeObjectFor('dark');
const gradients = {
  light: {
    brand: gradientStops(t.semantic.light['gradient-brand']),
    sky: gradientStops(t.semantic.light['gradient-sky']),
  },
  dark: {
    brand: gradientStops(t.semantic.dark['gradient-brand']),
    sky: gradientStops(t.semantic.dark['gradient-sky']),
  },
};
const radiusNum = Object.fromEntries(Object.entries(t.radius).map(([k, v]) => [k, remToNum(v)]));

// Style packs (playful/calm/toy3d) re-skin structure via numeric knobs. RN has
// no cascade for arbitrary tokens, so we expose them as JS numbers a PackScope
// context feeds to components (radius, chunky button depth, motion multiplier).
const num = (v) => parseFloat(v);
const packSkins = Object.fromEntries(
  Object.entries(t.packs).map(([name, m]) => [
    name,
    {
      radiusCard: remToNum(m['radius-card']),
      btnDepth: num(m['btn-depth']),
      borderW: num(m['border-w']),
      motionScale: num(m['motion-scale']),
    },
  ]),
);

// Accent packs re-hue the primary/ring family. Exposed as `--color-*` var maps
// (per light/dark) that PackScope layers via NativeWind vars(); blue = default.
const PRIMARY_KEYS = [
  'primary',
  'primary-hover',
  'primary-active',
  'primary-foreground',
  'primary-soft',
  'primary-soft-foreground',
  'ring',
];
const accentVars = Object.fromEntries(
  Object.entries(t.accents ?? {}).map(([name, modes]) => [
    name,
    {
      light: Object.fromEntries(
        PRIMARY_KEYS.map((k) => [`--color-${k}`, resolveColor(modes.light[k])]),
      ),
      dark: Object.fromEntries(
        PRIMARY_KEYS.map((k) => [`--color-${k}`, resolveColor(modes.dark[k])]),
      ),
    },
  ]),
);
// `blue` (brand default) resets the family back to the base semantic values.
accentVars.blue = {
  light: Object.fromEntries(
    PRIMARY_KEYS.map((k) => [`--color-${k}`, resolveColor(t.semantic.light[k])]),
  ),
  dark: Object.fromEntries(
    PRIMARY_KEYS.map((k) => [`--color-${k}`, resolveColor(t.semantic.dark[k])]),
  ),
};

const nativeTs = `${GENERATED}

/**
 * Bingoo design tokens — native (React Native) mirror. Generated from
 * tokens.json. Feed \`themeVars[scheme]\` to NativeWind's \`vars()\` on a wrapper
 * View so semantic classes (bg-primary, text-foreground…) swap by theme. Use the
 * resolved \`lightTheme\`/\`darkTheme\`/\`gradients\` for raw-color native APIs.
 */
export const themeVars = ${JSON.stringify(themeVars, null, 2)};

export const lightTheme = ${JSON.stringify(lightTheme, null, 2)};

export const darkTheme = ${JSON.stringify(darkTheme, null, 2)};

export const gradients = ${JSON.stringify(gradients, null, 2)};

export const themeColor = ${JSON.stringify(themeColor, null, 2)};

export const brand = ${JSON.stringify(brand, null, 2)};

export const radius = ${JSON.stringify(radiusNum, null, 2)};

export const packSkins = ${JSON.stringify(packSkins, null, 2)};

export const accentVars = ${JSON.stringify(accentVars, null, 2)};

export const font = {
  display: ${JSON.stringify(t.js.fontDisplay)},
  text: ${JSON.stringify(t.js.fontText)},
};
`;

const nativeDts = `${GENERATED}

type ColorToken = ${t.colorTokens.map((k) => JSON.stringify(k)).join(' | ')};
type Scheme = 'light' | 'dark';

export declare const themeVars: Record<Scheme, Record<string, string>>;
export declare const lightTheme: Record<ColorToken, string>;
export declare const darkTheme: Record<ColorToken, string>;
export declare const gradients: Record<Scheme, { brand: string[]; sky: string[] }>;
export declare const themeColor: { light: string; dark: string };
export declare const brand: Record<string, string>;
export declare const radius: Record<string, number>;
export declare const packSkins: Record<
  string,
  { radiusCard: number; btnDepth: number; borderW: number; motionScale: number }
>;
export declare const accentVars: Record<string, Record<Scheme, Record<string, string>>>;
export declare const font: { display: string; text: string };
`;

// NativeWind preset: semantic classes resolve to the CSS vars set by vars();
// primitive scales are literal so they work without a theme wrapper.
const presetColors = {
  transparent: 'transparent',
  white: '#ffffff',
  black: '#000000',
  ...Object.fromEntries(t.colorTokens.map((k) => [k, `var(--color-${k})`])),
  ...Object.fromEntries(Object.entries(t.color).map(([group, shades]) => [group, { ...shades }])),
};
const presetRadius = Object.fromEntries(Object.entries(t.radius).map(([k, v]) => [k, remToPx(v)]));
const presetFontSize = Object.fromEntries(
  Object.entries(t.text).map(([k, [size, lh]]) => [
    k,
    [remToPx(size), { lineHeight: remToPx(lh) }],
  ]),
);

const nativePreset = `${GENERATED}
/** @type {import('tailwindcss').Config} */
module.exports = {
  theme: {
    extend: {
      colors: ${JSON.stringify(presetColors, null, 6)},
      borderRadius: ${JSON.stringify(presetRadius, null, 6)},
      fontSize: ${JSON.stringify(presetFontSize, null, 6)},
      // RN/Fabric needs fontFamily as a STRING (an array throws
      // "expected string, had array"). These are the family names the app loads
      // via @expo-google-fonts (see apps/mobile). Weight-specific families are
      // applied per text variant in @bingoo/ui-native's Text.
      fontFamily: {
        display: ${JSON.stringify(t.native?.fontDisplay ?? 'Baloo2_700Bold')},
        sans: ${JSON.stringify(t.native?.fontText ?? 'BeVietnamPro_400Regular')},
      },
    },
  },
};
`;

/* ------------------------------- write --------------------------------- */
mkdirSync(join(root, 'dist'), { recursive: true });
mkdirSync(join(root, 'dist/native'), { recursive: true });
writeFileSync(join(root, 'dist/tokens.css'), css);
writeFileSync(join(root, 'dist/tokens.ts'), ts);
writeFileSync(join(root, 'dist/native/theme.js'), nativeTs);
writeFileSync(join(root, 'dist/native/theme.d.ts'), nativeDts);
writeFileSync(join(root, 'dist/native/preset.cjs'), nativePreset);
console.log(
  '@bingoo/tokens: generated dist/tokens.css + dist/tokens.ts + dist/native/{theme.js,theme.d.ts,preset.cjs}',
);
