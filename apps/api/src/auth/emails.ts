import { getEmail } from '../providers'

/**
 * Transactional auth emails (verification + password reset), sent through the
 * swappable email provider (getEmail → Resend today). Copy is bilingual and
 * chosen by the user's locale — no single hardcoded language (R4). Full email
 * i18n via @bingoo/i18n arrives with the wider notification work; this keeps P1
 * self-contained.
 *
 * Sending is best-effort: a missing/failing provider is logged, never thrown, so
 * an unconfigured email vendor can't turn a sign-up into a 500. In production the
 * provider is configured and /health/providers surfaces readiness.
 */

type Locale = 'vi' | 'en'
type Kind = 'verify' | 'reset'

interface AuthEmailUser {
  email?: string | null
  locale?: string | null
}

/** Default to Vietnamese (primary market); switch to English for `en*` locales. */
function pickLocale(locale: string | null | undefined): Locale {
  return locale?.toLowerCase().startsWith('en') ? 'en' : 'vi'
}

const COPY: Record<Kind, Record<Locale, { subject: string; heading: string; body: string; cta: string }>> = {
  verify: {
    vi: {
      subject: 'Xác minh email Bingoo của bạn',
      heading: 'Xác minh email',
      body: 'Nhấn nút bên dưới để xác minh địa chỉ email và kích hoạt tài khoản Bingoo của bạn. Liên kết sẽ hết hạn sau một thời gian ngắn.',
      cta: 'Xác minh email',
    },
    en: {
      subject: 'Verify your Bingoo email',
      heading: 'Verify your email',
      body: 'Tap the button below to verify your email address and activate your Bingoo account. This link expires shortly.',
      cta: 'Verify email',
    },
  },
  reset: {
    vi: {
      subject: 'Đặt lại mật khẩu Bingoo',
      heading: 'Đặt lại mật khẩu',
      body: 'Bạn (hoặc ai đó) vừa yêu cầu đặt lại mật khẩu. Nếu không phải bạn, hãy bỏ qua email này — mật khẩu của bạn không thay đổi.',
      cta: 'Đặt lại mật khẩu',
    },
    en: {
      subject: 'Reset your Bingoo password',
      heading: 'Reset your password',
      body: 'You (or someone) requested a password reset. If this wasn’t you, ignore this email — your password stays the same.',
      cta: 'Reset password',
    },
  },
}

function render(
  kind: Kind,
  user: AuthEmailUser,
  url: string,
): { subject: string; html: string; text: string } {
  const c = COPY[kind][pickLocale(user.locale)]
  // `url` is generated by Better Auth (safe); no user-controlled value is
  // interpolated into the HTML, so no escaping is required here.
  const html = `<!doctype html><html><body style="margin:0;padding:24px;font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif;background:#f6f7f9;color:#1a1a2e">
  <table role="presentation" width="100%" cellpadding="0" cellspacing="0"><tr><td align="center">
    <table role="presentation" width="100%" style="max-width:480px;background:#ffffff;border-radius:16px;padding:32px">
      <tr><td>
        <h1 style="margin:0 0 12px;font-size:20px">${c.heading}</h1>
        <p style="margin:0 0 24px;font-size:15px;line-height:1.6">${c.body}</p>
        <a href="${url}" style="display:inline-block;padding:12px 24px;background:#5b3df5;color:#ffffff;text-decoration:none;border-radius:12px;font-weight:600">${c.cta}</a>
        <p style="margin:24px 0 0;font-size:12px;color:#6b7280;word-break:break-all">${url}</p>
      </td></tr>
    </table>
  </td></tr></table>
</body></html>`
  const text = `${c.heading}\n\n${c.body}\n\n${c.cta}: ${url}`
  return { subject: c.subject, html, text }
}

/** Send an auth email; failures are logged and swallowed (see module doc). */
export async function sendAuthEmail(kind: Kind, user: AuthEmailUser, url: string): Promise<void> {
  if (!user.email) return
  try {
    await getEmail().send({ to: user.email, ...render(kind, user, url) })
  } catch (err) {
    console.error(`[auth-email] failed to send "${kind}":`, err instanceof Error ? err.message : err)
  }
}
