/**
 * Prompt catalog — the SINGLE place every LLM prompt is defined (no more inline
 * prompts scattered across services). Each entry has a stable id, a default
 * template (with `{{var}}` placeholders) and the variables it expects. The
 * default is overridable at RUNTIME via RemoteConfig (key `prompt:<id>`), so a
 * prompt can be hotfixed/tuned WITHOUT a release (R6). Add a new prompt = add one
 * entry here; nothing else in a feature needs to hardcode prompt text.
 */

export interface PromptDefinition {
  id: string
  description: string
  /** Placeholder names used in the template (documentation + admin UI hints). */
  variables: readonly string[]
  template: string
}

